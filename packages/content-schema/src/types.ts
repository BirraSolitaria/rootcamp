import { z } from 'zod';

// zod checks shape only. Lengths, counts, ID formats and cross-field rules
// (e.g. correctIndex within options) are checked by the content validator,
// which reports them with rule codes.

export const TheoryBlockSchema = z.discriminatedUnion('type', [
  z.strictObject({ type: z.literal('text'), text: z.string() }),
  z.strictObject({ type: z.literal('code'), code: z.string() }),
]);
export type TheoryBlock = z.infer<typeof TheoryBlockSchema>;

export const TheoryCardSchema = z.strictObject({
  title: z.string(),
  blocks: z.array(TheoryBlockSchema),
});
export type TheoryCard = z.infer<typeof TheoryCardSchema>;

const taskBase = {
  id: z.string(),
  explanation: z.string(),
};

export const SingleChoiceTaskSchema = z.strictObject({
  ...taskBase,
  type: z.literal('single_choice'),
  question: z.string(),
  options: z.array(z.string()),
  correctIndex: z.number().int().nonnegative(),
});

export const TrueFalseTaskSchema = z.strictObject({
  ...taskBase,
  type: z.literal('true_false'),
  statement: z.string(),
  answer: z.boolean(),
});

export const AssembleTaskSchema = z.strictObject({
  ...taskBase,
  type: z.literal('assemble'),
  prompt: z.string(),
  answer: z.array(z.string()),
  altAnswers: z.array(z.array(z.string())).optional(),
  distractors: z.array(z.string()),
});

export const FillBlankTaskSchema = z.strictObject({
  ...taskBase,
  type: z.literal('fill_blank'),
  prompt: z.string(),
  template: z.string(),
  acceptedAnswers: z.array(z.string()),
});

export const PairSchema = z.strictObject({ left: z.string(), right: z.string() });
export type Pair = z.infer<typeof PairSchema>;

export const MatchPairsTaskSchema = z.strictObject({
  ...taskBase,
  type: z.literal('match_pairs'),
  prompt: z.string(),
  pairs: z.array(PairSchema),
});

/** `steps` are listed in the correct order. */
export const OrderStepsTaskSchema = z.strictObject({
  ...taskBase,
  type: z.literal('order_steps'),
  prompt: z.string(),
  steps: z.array(z.string()),
});

/** Generated by the builder for a practice node; has no explanation (§4.2). */
export const TerminalPracticeTaskSchema = z.strictObject({
  id: z.string(),
  type: z.literal('terminal_practice'),
  practiceId: z.string(),
});

export const TaskSchema = z.discriminatedUnion('type', [
  SingleChoiceTaskSchema,
  TrueFalseTaskSchema,
  AssembleTaskSchema,
  FillBlankTaskSchema,
  MatchPairsTaskSchema,
  OrderStepsTaskSchema,
  TerminalPracticeTaskSchema,
]);

export type SingleChoiceTask = z.infer<typeof SingleChoiceTaskSchema>;
export type TrueFalseTask = z.infer<typeof TrueFalseTaskSchema>;
export type AssembleTask = z.infer<typeof AssembleTaskSchema>;
export type FillBlankTask = z.infer<typeof FillBlankTaskSchema>;
export type MatchPairsTask = z.infer<typeof MatchPairsTaskSchema>;
export type OrderStepsTask = z.infer<typeof OrderStepsTaskSchema>;
export type TerminalPracticeTask = z.infer<typeof TerminalPracticeTaskSchema>;
export type Task = z.infer<typeof TaskSchema>;
export type TaskType = Task['type'];

export const TASK_TYPES = [
  'single_choice',
  'true_false',
  'assemble',
  'fill_blank',
  'match_pairs',
  'order_steps',
  'terminal_practice',
] as const satisfies readonly TaskType[];

export type InteractiveTaskType = Exclude<TaskType, 'terminal_practice'>;

/** Task types answered inside a lesson (everything except terminal_practice). */
export const INTERACTIVE_TASK_TYPES = [
  'single_choice',
  'true_false',
  'assemble',
  'fill_blank',
  'match_pairs',
  'order_steps',
] as const satisfies readonly InteractiveTaskType[];

/** User answer (UI → answer check). terminal_practice is solved via the practice flow. */
export type UserAnswer =
  | { type: 'single_choice'; selectedIndex: number } // index in the original options
  | { type: 'true_false'; value: boolean }
  | { type: 'assemble'; tokens: string[] } // chosen tile texts, in order
  | { type: 'fill_blank'; text: string }
  | { type: 'match_pairs'; pairs: Pair[] }
  | { type: 'order_steps'; order: string[] }; // step texts in the chosen order

export interface CheckResult {
  correct: boolean;
  /** Human-readable correct answer for the result banner. */
  correctAnswerText: string;
}

export interface ValidationError {
  path: string;
  rule: string;
  message: string;
  severity: 'error' | 'warning';
}
